/* ------------------------------------------------------------------ */
/*  Types                                                              */
/* ------------------------------------------------------------------ */

/**
 * A single figure that can be dropped into a factsheet widget. Figures are
 * screenshots extracted from the source PDF (see
 * scripts/factsheet-verify/extract_figure_images.py) so the factsheet
 * preserves the original ESABCC chart exactly. The legacy chart-based
 * fields (chartType, data) are kept optional for cases where we want to
 * synthesise a chart instead of using the PDF screenshot.
 */
export interface ReportFigure {
  id: string;
  title: string;
  sourceNote: string;
  /** Figure number as it appears in the source PDF (e.g. "27"). */
  figureNumber?: string;
  /** Page reference, e.g. "p.119". */
  pageRef?: string;
  /** Path (under /public) to the PDF-extracted screenshot. */
  imageSrc?: string;
  /** Chart-only crop (caption + chart, without Source/Notes lines). */
  imageSrcChart?: string;
  /** Source/Notes-only crop, used when the notes are deferred to the end of the factsheet. */
  imageSrcNotes?: string;
  /** Chart type for synthesised charts (optional when imageSrc is set). */
  chartType?: 'bar' | 'line' | 'doughnut' | 'pie' | 'radar';
  data?: {
    labels: string[];
    datasets: {
      label: string;
      data: (number | null)[];
      backgroundColor?: string | string[];
      borderColor?: string | string[];
      borderWidth?: number;
      borderDash?: number[];
      fill?: boolean | string;
      tension?: number;
      stack?: string;
      pointRadius?: number;
      pointBackgroundColor?: string;
      spanGaps?: boolean;
    }[];
  };
}

export interface ReportData {
  id: string;
  title: string;
  shortTitle: string;
  date: string;
  year: number;
  pdfFilename: string;
  url: string;
  shortSummary: string;
  longSummary: string;
  keyFindings: string[];
  /**
   * Headline recommendations as they appear in the report's executive
   * summary / recommendations section. Attribution: ESABCC reports,
   * "Reproduction is authorised provided the source is acknowledged".
   */
  recommendations: string[];
  figures: ReportFigure[];
  accentColor: string;
}

