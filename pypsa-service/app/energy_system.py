"""
EU electricity system optimization — 30-country network (PyPSA).

A full 30-bus network where each bus represents one European country
(EU-27 + Norway, Switzerland, United Kingdom). Each country hosts its
own portfolio of generator technologies (wind, solar, nuclear, hydro,
gas, coal, battery, hydrogen) with country-specific capacity factors,
technology potentials and demand. Cross-border interconnectors are
modelled as transport links with NTC capacities from ENTSO-E TYNDP 2022.

The model solves a joint capacity-expansion + dispatch LP over a small
number of representative "snapshots" (e.g. 48 h) and returns:
    - installed capacity per (country, technology)
    - total dispatch per technology
    - hourly dispatch and load time series
    - cross-border flows
    - CO2 emissions
    - levelised and marginal cost
    - shadow price of the CO2 constraint (if any)

The model is solved with the real `pypsa` library, which builds a `linopy`
problem and dispatches it to HiGHS via `highspy`. There is no fallback —
if PyPSA is not installed the service will refuse to run.
"""

