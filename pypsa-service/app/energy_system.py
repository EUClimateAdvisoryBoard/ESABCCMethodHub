# Every country is a bus — ISO-2 codes
BUSES: List[str] = [c.iso2 for c in COUNTRIES]

# Annual electricity demand per country (TWh/yr, 2030 reference)
ANNUAL_DEMAND_TWH: Dict[str, float] = {c.iso2: c.demand_twh for c in COUNTRIES}

# Load shape multipliers for a 48-hour representative window (winter day +
# summer day, approximate EU load curve). Shifted by ±1 h longitude to
# capture timezone effects on the diurnal curve.
_BASE_LOAD_48H: List[float] = [
    0.72, 0.70, 0.69, 0.70, 0.74, 0.82, 0.92, 1.02, 1.08, 1.10, 1.09, 1.07,
    1.04, 1.02, 1.02, 1.04, 1.08, 1.12, 1.15, 1.12, 1.05, 0.95, 0.85, 0.78,
    0.75, 0.72, 0.71, 0.72, 0.76, 0.84, 0.94, 1.03, 1.06, 1.05, 1.02, 0.99,
    0.96, 0.95, 0.96, 0.99, 1.04, 1.09, 1.11, 1.08, 1.00, 0.90, 0.81, 0.74,
]


def _shift_load(base: List[float], lon: float) -> List[float]:
    """Shift a diurnal load shape by the country's longitude (timezone proxy).

    Positive longitude → earlier sunrise/peak vs UTC reference.
    Each 15° of longitude ≈ 1 hour of shift.
    """
    shift = round(lon / 15.0)
    arr = list(base)
    # Shift each 24-h block independently to preserve diurnal structure
    day1 = arr[:24]
    day2 = arr[24:48] if len(arr) >= 48 else day1[:]
    day1 = day1[-shift:] + day1[:-shift] if shift else day1
    day2 = day2[-shift:] + day2[:-shift] if shift else day2
    return day1 + day2


LOAD_SHAPE: Dict[str, List[float]] = {
    c.iso2: _shift_load(_BASE_LOAD_48H, c.lon) for c in COUNTRIES
}

# Base wind CF curve (EU-wide mean 48 h pattern). Per-country CFs are
# generated by scaling this with CountrySpec.wind_onshore_scale.
_BASE_WIND_CF_48H: List[float] = [
    0.38, 0.40, 0.42, 0.44, 0.45, 0.43, 0.40, 0.37, 0.34, 0.32, 0.30, 0.29,
    0.30, 0.31, 0.33, 0.35, 0.37, 0.39, 0.40, 0.41, 0.41, 0.40, 0.38, 0.36,
    0.34, 0.32, 0.30, 0.29, 0.29, 0.30, 0.32, 0.35, 0.37, 0.39, 0.40, 0.40,
    0.39, 0.38, 0.37, 0.36, 0.34, 0.33, 0.31, 0.30, 0.30, 0.30, 0.31, 0.32,
]


def _scale_wind_cf(base: List[float], scale: float) -> List[float]:
    """Apply a country-specific wind capacity-factor multiplier, capped at 1."""
    return [min(1.0, v * scale) for v in base]


WIND_CF: Dict[str, List[float]] = {
    c.iso2: _scale_wind_cf(_BASE_WIND_CF_48H, c.wind_onshore_scale) for c in COUNTRIES
}

WIND_OFFSHORE_CF: Dict[str, List[float]] = {
    c.iso2: _scale_wind_cf(_BASE_WIND_CF_48H, c.wind_offshore_scale)
    for c in COUNTRIES if c.coastal and c.wind_offshore_scale > 0
}


# Solar CF timeseries per country (48 h — two daylight bell curves).
# Peak CF is 0.55 × solar_scale; the Gaussian shape is shifted by longitude.
def _solar_curve(peak: float, lon: float = 0.0) -> List[float]:
    # Solar noon shifts ~1 h per 15° longitude
    noon_shift = lon / 15.0
    cf: List[float] = []
    for day in range(2):
        for hour in range(24):
            x = (hour - (13.0 + noon_shift)) / 5.0
            v = peak * math.exp(-x * x)
            cf.append(max(0.0, min(peak, v)))
    return cf


SOLAR_CF: Dict[str, List[float]] = {
    c.iso2: _solar_curve(0.55 * c.solar_scale, c.lon) for c in COUNTRIES
}

# Country-level interconnectors — from eu_countries.py (ENTSO-E NTC)
INTERCONNECTORS: List[Tuple[str, str, float]] = [
    (a, b, cap) for a, b, cap, _kind in COUNTRY_INTERCONNECTORS
]

# Pre-compute per-country technology potentials (GW)
POTENTIALS: Dict[str, Dict[str, float]] = {
    c.iso2: country_potentials(c) for c in COUNTRIES
}


@dataclass
class Technology:
    name: str
    capex_eur_per_kw: float       # overnight investment cost
    fom_eur_per_kw_yr: float      # fixed O&M
    vom_eur_per_mwh: float        # variable O&M
    fuel_eur_per_mwh: float       # fuel at input level
    efficiency: float              # electrical efficiency (fuel→elec)
    co2_t_per_mwh_fuel: float     # fuel emission factor
    lifetime_years: int
    variable: bool = False        # True = VRE, False = dispatchable
    max_cf: float = 1.0           # cap for dispatchable techs
    available: bool = True        # toggled by user assumptions
    # Per-bus potential (GW). A value of None = effectively unconstrained.
    potential_gw: Optional[Dict[str, float]] = None


def annuity(capex: float, lifetime: int, discount: float) -> float:
    if discount == 0:
        return capex / lifetime
    return capex * discount / (1.0 - (1.0 + discount) ** -lifetime)


# Maps our internal tech IDs to the canonical `technology` name used in
# PyPSA/technology-data (https://github.com/PyPSA/technology-data). When a
# real costs_YYYY.csv file is available the numbers below are overwritten
# with the peer-reviewed upstream values.
_PYPSA_EUR_TECH_NAMES: Dict[str, str] = {
    "onwind":   "onwind",
    "offwind":  "offwind-ac",
    "solar":    "solar",
    "nuclear":  "nuclear",
    "gas_ocgt": "OCGT",
    "gas_ccgt": "CCGT",
    "coal":     "coal",
    "hydro":    "hydro",
    "battery":  "battery inverter",
    "h2":       "OCGT",  # hydrogen-ready turbine proxied via OCGT capex
}


def _apply_real_costs(techs: Dict[str, Technology], year: int = 2030) -> Optional[str]:
    """Override the baked-in costs with real PyPSA-Eur technology-data values.

    Returns the data-source string if the overlay was applied, else None.
    """
    real = load_pypsa_eur_costs(year)
    if not real:
        return None
    for tid, upstream in _PYPSA_EUR_TECH_NAMES.items():
        if tid not in techs or upstream not in real:
            continue
        params = real[upstream]
        t = techs[tid]
        if "investment" in params:
            # technology-data reports investment in EUR/kW
            t.capex_eur_per_kw = float(params["investment"])
        if "FOM" in params:
            # FOM is % of investment per year → convert to EUR/kW/yr
            t.fom_eur_per_kw_yr = float(params["FOM"]) / 100.0 * t.capex_eur_per_kw
        if "VOM" in params:
            t.vom_eur_per_mwh = float(params["VOM"])
        if "lifetime" in params:
            t.lifetime_years = int(params["lifetime"])
        if "efficiency" in params:
            t.efficiency = float(params["efficiency"])
        if "fuel" in params:
            t.fuel_eur_per_mwh = float(params["fuel"])
        if "CO2 intensity" in params:
            t.co2_t_per_mwh_fuel = float(params["CO2 intensity"])
    return f"PyPSA-Eur technology-data v0.14.0 (costs_{year}.csv)"


def build_technologies(assumptions: "Assumptions") -> Tuple[Dict[str, Technology], Optional[str]]:
    """Build the technology portfolio.

    Returns (techs, costs_source). ``costs_source`` is a provenance string
    (non-None if real PyPSA-Eur technology-data costs were applied).
    """
    techs: Dict[str, Technology] = {
        "onwind":   Technology("Onshore Wind", 1100,  25, 1, 0,    1.0,  0.0, 25, variable=True),
        "offwind":  Technology("Offshore Wind",2400,  80, 2, 0,    1.0,  0.0, 25, variable=True),
        "solar":    Technology("Solar PV",      600,  15, 0, 0,    1.0,  0.0, 25, variable=True),
        "nuclear":  Technology("Nuclear",      6500, 110, 3, 6,    0.33, 0.0, 60, max_cf=0.90),
        "gas_ocgt": Technology("Gas OCGT",      500,  10, 3, 28,   0.40, 0.20, 25),
        "gas_ccgt": Technology("Gas CCGT",      900,  15, 3, 28,   0.60, 0.20, 25),
        "coal":     Technology("Coal",         1600,  30, 4, 14,   0.42, 0.34, 35),
        "hydro":    Technology("Hydro Reservoir",2200, 40, 1, 0,  1.0,  0.0, 80, max_cf=0.40),
        "battery":  Technology("Battery (4h)", 1400,  15, 0, 0,    0.88, 0.0, 15, max_cf=0.25),
        "h2":       Technology("Hydrogen Turbine",800, 15, 4, 90,  0.45, 0.0, 25),
    }
    # Overlay with real PyPSA-Eur technology-data values if available
    costs_source = _apply_real_costs(techs, year=assumptions.year)

    # Build per-country potentials from eu_countries.country_potentials()
    for tid in techs:
        pot: Dict[str, float] = {}
        for iso2 in BUSES:
            cpot = POTENTIALS.get(iso2, {})
            pot[iso2] = cpot.get(tid, 0.0)
        techs[tid].potential_gw = pot

    if not assumptions.allow_nuclear:
        techs["nuclear"].available = False
    if assumptions.phase_out_coal:
        techs["coal"].available = False
    if not assumptions.allow_storage:
        techs["battery"].available = False
    if not assumptions.allow_hydrogen:
        techs["h2"].available = False
    return techs, costs_source


