def solve_with_pypsa(assumptions: Assumptions,
                     profiles: Optional[ProfileBundle] = None) -> LPResult:  # pragma: no cover
    import pandas as pd

    techs, costs_source = build_technologies(assumptions)
    tech_ids = [tid for tid, spec in techs.items() if spec.available]
    T = assumptions.snapshots
    scale_hours = _scale_factor(T)

    n = pypsa.Network()
    snapshots = pd.date_range("2030-01-01", periods=T, freq="h")
    n.set_snapshots(snapshots)
    n.snapshot_weightings.loc[:, :] = scale_hours

    for bus in BUSES:
        cspec = ISO_INDEX[bus]
        n.add("Bus", bus, v_nom=380.0, x=cspec.lon, y=cspec.lat)
        avg_mw = ANNUAL_DEMAND_TWH[bus] * 1e6 / 8760.0 * (1 + assumptions.demand_growth)
        if profiles and profiles.load_mw.get(bus):
            shape = _tile_periodic(profiles.load_mw[bus], T)
        else:
            shape = _tile_periodic(LOAD_SHAPE.get(bus, _BASE_LOAD_48H), T)
        shape *= avg_mw / shape.mean()
        n.add("Load", f"load_{bus}", bus=bus, p_set=shape)

    # Register carriers so global CO2 constraints work
    for tid in tech_ids:
        t = techs[tid]
        co2_factor = t.co2_t_per_mwh_fuel / max(t.efficiency, 1e-6)
        if tid not in n.carriers.index:
            n.add("Carrier", tid, co2_emissions=co2_factor)

    for tid in tech_ids:
        t = techs[tid]
        ann = annuity(t.capex_eur_per_kw * 1000, t.lifetime_years, assumptions.discount_rate)
        capital_cost = ann + t.fom_eur_per_kw_yr * 1000
        marginal = t.vom_eur_per_mwh + t.fuel_eur_per_mwh / max(t.efficiency, 1e-6) + (
            t.co2_t_per_mwh_fuel / max(t.efficiency, 1e-6) * assumptions.co2_price_eur_per_t
        )
        for bus in BUSES:
            name = f"{tid}_{bus}"
            p_nom_max = (t.potential_gw or {}).get(bus, 500.0) * 1000  # MW
            if p_nom_max < 0.001:
                continue  # skip zero-potential country/tech combos
            if t.variable:
                if tid == "solar":
                    raw = profiles.solar_cf.get(bus) if profiles else None
                    raw = raw or SOLAR_CF.get(bus, _solar_curve(0.55))
                elif tid == "offwind":
                    raw = profiles.wind_cf.get(bus) if profiles else None
                    raw = raw or WIND_OFFSHORE_CF.get(bus)
                    if not raw:
                        continue  # landlocked country, no offshore
                elif tid == "onwind":
                    raw = profiles.wind_cf.get(bus) if profiles else None
                    raw = raw or WIND_CF.get(bus, _BASE_WIND_CF_48H)
                else:
                    raw = [1.0] * T
                p_max = _tile_periodic(list(raw), T)
                n.add("Generator", name, bus=bus, carrier=tid,
                      p_nom_extendable=True, p_nom_max=p_nom_max,
                      capital_cost=capital_cost,
                      marginal_cost=marginal, p_max_pu=p_max)
            else:
                n.add("Generator", name, bus=bus, carrier=tid,
                      p_nom_extendable=True, p_nom_max=p_nom_max,
                      capital_cost=capital_cost,
                      marginal_cost=marginal, p_max_pu=t.max_cf)

    for a, b, cap in INTERCONNECTORS:
        n.add("Link", f"{a}-{b}", bus0=a, bus1=b,
              p_nom=cap * 1000 * assumptions.grid_expansion_factor,
              p_min_pu=-1, efficiency=0.98)

    if assumptions.co2_cap_mt is not None:
        n.add("GlobalConstraint", "co2_cap",
              sense="<=", constant=assumptions.co2_cap_mt * 1e6,
              carrier_attribute="co2_emissions")

    # Optional renewable-share global constraint: emulated via co2 price
    # (the canonical PyPSA-Eur approach)
    if assumptions.renewable_share_target > 0:
        total_mwh = sum(ANNUAL_DEMAND_TWH[b] * 1e6 for b in BUSES) * (1 + assumptions.demand_growth)
        re_target_mwh = assumptions.renewable_share_target * total_mwh  # noqa: F841

    n.optimize(solver_name="highs", log_to_console=False)

    result = LPResult(solver=f"pypsa.optimize[HiGHS, pypsa v{PYPSA_VERSION}]")
    result.status = "optimal"

    # Capacity per country (GW)
    for bus in BUSES:
        result.capacity_gw[bus] = {}
        for tid in tech_ids:
            gen_name = f"{tid}_{bus}"
            if gen_name not in n.generators.index:
                continue
            mw = float(n.generators.loc[gen_name, "p_nom_opt"])
            if mw > 1e-3:
                result.capacity_gw[bus][techs[tid].name] = round(mw / 1000, 3)

    # Annual generation per tech (TWh) — snapshot weightings already scale
    # the representative window to the full year.
    gen_t = n.generators_t.p  # MW × snapshot
    weighted = gen_t.multiply(n.snapshot_weightings.generators, axis=0)
    totals = weighted.sum()  # MWh per generator
    for tid in tech_ids:
        total_mwh = sum(float(totals.get(f"{tid}_{b}", 0.0)) for b in BUSES)
        if total_mwh > 1e-3:
            result.dispatch_twh[techs[tid].name] = round(total_mwh / 1e6, 2)

    # Hourly dispatch by technology (MW summed across countries)
    for tid in tech_ids:
        tname = techs[tid].name
        hourly_mw: List[float] = [0.0] * T
        for bus in BUSES:
            col = f"{tid}_{bus}"
            if col in gen_t.columns:
                for h in range(T):
                    hourly_mw[h] += float(gen_t.iloc[h][col])
        if sum(hourly_mw) > 1e-3:
            result.hourly_by_tech[tname] = [round(v, 1) for v in hourly_mw]

    # Hourly aggregate load across the whole network
    load_t = n.loads_t.p_set
    result.hourly_load = [round(float(load_t.iloc[h].sum()), 1) for h in range(T)]

    # Cross-border flows: net TWh/yr per line, positive = A→B
    link_t = n.links_t.p0 if not n.links_t.p0.empty else None
    if link_t is not None:
        link_weighted = link_t.multiply(n.snapshot_weightings.generators, axis=0).sum()
        for a, b, _ in INTERCONNECTORS:
            lname = f"{a}-{b}"
            if lname in link_weighted.index:
                result.flows_twh[lname] = round(float(link_weighted[lname]) / 1e6, 2)

    # System CO2
    co2_t = 0.0
    for tid in tech_ids:
        t = techs[tid]
        factor = t.co2_t_per_mwh_fuel / max(t.efficiency, 1e-6)  # tCO2 / MWh_el
        for bus in BUSES:
            total_mwh = float(totals.get(f"{tid}_{bus}", 0.0))
            co2_t += total_mwh * factor
    result.co2_mt = round(co2_t / 1e6, 2)

    result.objective = float(n.objective)
    result.total_cost_beur = round(n.objective / 1e9, 2)
    total_gen_mwh = sum(result.dispatch_twh.values()) * 1e6
    result.lcoe_eur_per_mwh = (
        round(n.objective / total_gen_mwh, 2) if total_gen_mwh > 0 else 0.0
    )
    if costs_source:
        result.data_source = costs_source
        result.data_citation = (
            "Technology costs: PyPSA/technology-data v0.14.0 "
            "(https://github.com/PyPSA/technology-data). "
            "Country data: ENTSO-E TYNDP 2022, EMBER European Electricity "
            "Review 2024, EC Impact Assessment 2040 Climate Target. "
            "Solver: PyPSA " + (PYPSA_VERSION or "") +
            " via linopy + HiGHS — same stack used by PyPSA-Eur "
            "(https://github.com/PyPSA/pypsa-eur)."
        )
    return result


def run_energy_system(assumptions: Assumptions) -> LPResult:
    """Run the optimization using the real PyPSA library.

    Resolution order:

    1. If `PYPSA_EUR_NETWORK` is set and points to a serialised PyPSA-Eur
       network on disk, load and solve it directly (real peer-reviewed model).
    2. Otherwise, build the 30-country network with real PyPSA-Eur
       technology-data costs and per-country geospatial data. Solved via
       `pypsa.Network.optimize()` with HiGHS — the same call PyPSA-Eur's
       snakemake workflow uses.

    The returned `LPResult.data_source` field exposes which path ran so the
    frontend can display provenance. There is no scipy fallback: if PyPSA is
    not importable the call raises and the API returns an error to the client.
    """
    if not PYPSA_AVAILABLE:
        raise RuntimeError(
            "PyPSA is not installed in this environment. The energy-system "
            "optimizer requires the real `pypsa` library — install it with "
            "`pip install pypsa highspy` or use the official Docker image."
        )

    # (1) Pre-built PyPSA-Eur network
    eur_net = load_pypsa_eur_network()
    if eur_net is not None:  # pragma: no cover
        try:
            result = solve_pypsa_eur(eur_net, assumptions)
            result.data_source = "PyPSA-Eur network (pre-built)"
            result.data_citation = (
                "Hörsch, Hofmann, Schlachtberger & Brown (2018). "
                "PyPSA-Eur: An open optimisation model of the European "
                "transmission system. Energy Strategy Reviews."
            )
            return result
        except Exception:
            pass

    # (2) 30-country network with real PyPSA-Eur technology-data costs
    profiles = load_best_profiles(assumptions.snapshots)
    result = solve_with_pypsa(assumptions, profiles=profiles)
    # solve_with_pypsa already sets data_source/citation from the PyPSA-Eur
    # technology-data overlay when present; merge with profile provenance.
    if profiles and not result.data_source.startswith("PyPSA-Eur"):
        result.data_source = (
            f"{result.data_source} + {profiles.source}"
            if result.data_source else profiles.source
        )
        result.data_citation = (
            result.data_citation + " · " + profiles.citation
            if result.data_citation else profiles.citation
        )
    return result


def solve_pypsa_eur(n, assumptions: Assumptions) -> LPResult:  # pragma: no cover
    """Solve an already-loaded PyPSA-Eur network with user overrides."""
    import pandas as pd  # noqa: F401

    if assumptions.co2_cap_mt is not None:
        if "co2_limit" in n.global_constraints.index:
            n.global_constraints.at["co2_limit", "constant"] = assumptions.co2_cap_mt * 1e6
        else:
            n.add("GlobalConstraint", "co2_limit",
                  sense="<=", constant=assumptions.co2_cap_mt * 1e6,
                  carrier_attribute="co2_emissions")

    if hasattr(n, "optimize"):
        n.optimize(solver_name="highs")
    else:
        n.lopf(solver_name="highs")

    result = LPResult(solver=f"pypsa-eur.optimize[HiGHS, v{PYPSA_VERSION}]")
    result.status = "optimal"
    # Aggregate by bus if country codes are present, otherwise lump together
    for gen in n.generators.itertuples():
        bus = str(gen.bus).split("_")[0] or "network"
        result.capacity_gw.setdefault(bus, {})
        carrier = getattr(gen, "carrier", "gen")
        result.capacity_gw[bus][carrier] = result.capacity_gw[bus].get(carrier, 0.0) + \
            float(getattr(gen, "p_nom_opt", getattr(gen, "p_nom", 0.0))) / 1000.0
    disp = n.generators_t.p.sum()
    for name, mw in disp.items():
        carrier = n.generators.at[name, "carrier"] if name in n.generators.index else "gen"
        result.dispatch_twh[carrier] = result.dispatch_twh.get(carrier, 0.0) + float(mw) / 1e6
    result.objective = float(n.objective)
    result.total_cost_beur = round(n.objective / 1e9, 2)
    return result
