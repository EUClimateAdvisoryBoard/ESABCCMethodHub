@dataclass
class Assumptions:
    co2_price_eur_per_t: float = 100.0
    renewable_share_target: float = 0.0        # 0..1, hard lower bound on VRE+hydro
    co2_cap_mt: Optional[float] = None         # optional absolute CO2 cap (Mt/yr)
    allow_nuclear: bool = True
    phase_out_coal: bool = True
    allow_storage: bool = True
    allow_hydrogen: bool = True
    grid_expansion_factor: float = 1.0         # multiplier on interconnector caps
    demand_growth: float = 0.0                  # fractional change vs. reference
    discount_rate: float = 0.05
    snapshots: int = 48                         # 48 h representative window
    year: int = 2030
    scenario_name: str = "Custom"


# ---------------------------------------------------------------------------
# Result dataclass
