@dataclass
class LPResult:
    capacity_gw: Dict[str, Dict[str, float]] = field(default_factory=dict)
    dispatch_twh: Dict[str, float] = field(default_factory=dict)
    hourly_by_tech: Dict[str, List[float]] = field(default_factory=dict)
    hourly_load: List[float] = field(default_factory=list)
    flows_twh: Dict[str, float] = field(default_factory=dict)
    co2_mt: float = 0.0
    total_cost_beur: float = 0.0
    lcoe_eur_per_mwh: float = 0.0
    objective: float = 0.0
    solver: str = "pypsa.optimize[HiGHS]"
    data_source: str = "synthetic"
    data_citation: str = ""
    status: str = "ok"


def _scale_factor(snapshots: int) -> float:
    """Scale a representative window to an annual total (8760 h)."""
    return 8760.0 / snapshots


def _tile_periodic(values: List[float], T: int) -> np.ndarray:
    """Tile a short periodic shape (e.g. 48 h diurnal) to length T.

    The repository ships 48 h synthetic load and capacity-factor curves
    representing two diurnal cycles. When the user requests a longer
    representative window (T = 72, 96, 168 …) we have to repeat the
    diurnal pattern instead of slicing — otherwise the array is too
    short and PyPSA raises `Data for p_set has length 48 but expected
    72 for each snapshot`. Tiling preserves the diurnal physics.
    """
    arr = np.asarray(values, dtype=float)
    if arr.size == 0:
        return np.zeros(T, dtype=float)
    if arr.size >= T:
        return arr[:T]
    reps = int(np.ceil(T / arr.size))
    return np.tile(arr, reps)[:T]




