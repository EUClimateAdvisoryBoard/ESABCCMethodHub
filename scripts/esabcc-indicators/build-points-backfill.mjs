#!/usr/bin/env node
/**
 * Emit an idempotent migration that backfills the post-report ("afterReport")
 * indicator data points into Supabase `pw_indicator_points`.
 * ---------------------------------------------------------------------------
 * Why this exists
 * ---------------
 * In production the Indicator Database reads from the `pw_indicator_points`
 * table, NOT from the bundled `src/data/esabcc-indicators.ts`. Those rows are
 * seeded once by `041_seed_esabcc_report_indicators.sql` (years up to ~2022),
 * and the app-level seeder in `src/lib/project-workspace/db.ts` only inserts an
 * indicator's points when the indicator id is brand-new — so for an indicator
 * that already exists it never adds later years.
 *
 * The monthly `refresh-from-sources.mjs` job writes the new years into the TS
 * file (flagged `afterReport: true`), but nothing pushed them into the DB.
 * That is why the live database stayed frozen at the original seed while the
 * code carried 2023/2024 values.
 *
 * This script regenerates the backfill migration from the current TS data, so
 * each refresh PR also carries the matching DB update. The insert is
 * `on conflict (indicator_id, year) do nothing`: it only adds missing years and
 * never overwrites an existing row, so re-applying it is always safe.
 *
 * Usage:  node scripts/esabcc-indicators/build-points-backfill.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const MIGRATION_NAME = '055_backfill_indicator_points.sql';
const OUT = join(ROOT, 'supabase', 'migrations', MIGRATION_NAME);
const COMBINED = join(ROOT, 'supabase', 'combined_migrations.sql');

// Data files whose `afterReport` points should be mirrored into the DB.
const SOURCES = [
  join(ROOT, 'src', 'data', 'esabcc-indicators.ts'),
  join(ROOT, 'src', 'data', 'ecno-indicators.ts'),
];

const ID_RE = /id:\s*'([^']+)'/g;
const POINT_RE = /\{\s*year:\s*(-?\d+),\s*value:\s*(-?[\d.]+),\s*afterReport:\s*true\s*\}/g;

/** Format a value the way 041 / build-sql.py do (precision by magnitude). */
function num(v) {
  if (v === 0) return '0';
  const av = Math.abs(v);
  if (av >= 100) return v.toFixed(1);
  if (av >= 10) return v.toFixed(3);
  if (av >= 1) return v.toFixed(4);
  return v.toFixed(5);
}

/** Extract [{ id, points: [{year,value}] }] for every indicator with new years. */
function extract(src) {
  const out = [];
  let m;
  ID_RE.lastIndex = 0;
  const ids = [];
  while ((m = ID_RE.exec(src))) ids.push({ id: m[1], at: m.index });
  for (let i = 0; i < ids.length; i++) {
    const start = ids[i].at;
    const end = i + 1 < ids.length ? ids[i + 1].at : src.length;
    const block = src.slice(start, end);
    const points = [];
    let p;
    POINT_RE.lastIndex = 0;
    while ((p = POINT_RE.exec(block))) {
      points.push({ year: Number(p[1]), value: Number(p[2]) });
    }
    if (points.length) out.push({ id: ids[i].id, points });
  }
  return out;
}

async function main() {
  const indicators = [];
  for (const file of SOURCES) {
    indicators.push(...extract(await readFile(file, 'utf8')));
  }
  indicators.sort((a, b) => a.id.localeCompare(b.id));

  const rows = [];
  for (const ind of indicators) {
    for (const pt of ind.points) {
      rows.push(`  ('${ind.id.replace(/'/g, "''")}', ${pt.year}, ${num(pt.value)})`);
    }
  }

  const header =
    '-- ─────────────────────────────────────────────────────────────────────────────\n' +
    '-- Backfill the post-report ("afterReport") indicator data points into\n' +
    '-- pw_indicator_points.\n' +
    '--\n' +
    '-- Generated by scripts/esabcc-indicators/build-points-backfill.mjs from the\n' +
    '-- bundled src/data/*-indicators.ts series. The original seed migration\n' +
    '-- (041_seed_esabcc_report_indicators.sql) only went up to 2022; the monthly\n' +
    '-- Eurostat/EEA refresh adds later years to the TS file but the app-level\n' +
    '-- seeder never pushes them into an already-seeded DB. This migration closes\n' +
    '-- that gap.\n' +
    '--\n' +
    '-- Idempotent: on conflict (indicator_id, year) do nothing — only missing\n' +
    '-- years are inserted, existing rows are never overwritten. Re-run after each\n' +
    '-- refresh (the generator overwrites this file with the current years).\n' +
    '-- ─────────────────────────────────────────────────────────────────────────────\n\n' +
    'insert into public.pw_indicator_points (indicator_id, year, value)\nvalues\n';

  const sql = header + rows.join(',\n') + '\non conflict (indicator_id, year) do nothing;\n';
  await writeFile(OUT, sql);
  console.log(`Wrote ${OUT} — ${rows.length} post-report points across ${indicators.length} indicators.`);

  await syncCombined(sql);
}

/**
 * Keep the mirrored migration block inside supabase/combined_migrations.sql in
 * sync. That file is the one-shot apply path (pasted into the Supabase SQL
 * Editor); if it isn't updated, the new years never run for anyone using it —
 * which is exactly how the backfill silently went missing after a refresh.
 * Replaces the existing block (this migration is last in the file) or appends a
 * fresh one, and bumps the banner range. Other migrations are left untouched.
 */
async function syncCombined(sql) {
  let combined;
  try {
    combined = await readFile(COMBINED, 'utf8');
  } catch {
    console.log(`(skip combined sync: ${COMBINED} not found)`);
    return;
  }
  const RULE = combined.split('\n').find(l => /^-- -{20,}$/.test(l));
  if (!RULE) throw new Error('combined_migrations.sql: separator line not found');

  const marker = `\n${RULE}\n-- ${MIGRATION_NAME}\n`;
  const at = combined.indexOf(marker);
  // This migration is the highest-numbered, so its block runs to EOF — drop
  // everything from the marker onward, then re-append the fresh block.
  if (at >= 0) combined = combined.slice(0, at);
  combined = combined.replace(/\s*$/, '\n');
  combined += `\n${RULE}\n-- ${MIGRATION_NAME}\n${RULE}\n\n${sql.replace(/\s*$/, '')}\n`;

  // Bump the banner's upper bound to this migration's number.
  const num = MIGRATION_NAME.match(/^(\d+)_/)[1];
  combined = combined.replace(
    /-- COMBINED MIGRATIONS \((\d+) -> \d+\)/,
    `-- COMBINED MIGRATIONS ($1 -> ${num})`
  );

  await writeFile(COMBINED, combined);
  console.log(`Synced ${MIGRATION_NAME} block into ${COMBINED}.`);
}

main().catch(e => { console.error(e); process.exit(1); });
