// ---------------------------------------------------------------------------
// Measurement-family catalogue for M·53 (Policy Targets → Indicator Flow Charts).
//
// One entry per MEASURABLE CONCEPT that an EU climate target can be assessed
// against. Each family says three things:
//
//   1. WHAT is measured — label, unit, sector, and the direction of progress.
//   2. WITH WHAT — `indicatorIds`, the curated MethodHub series that already
//      measure it (ids from src/data/{esabcc,ecno,advanced,beta}-indicators.ts,
//      validated at build time). Empty when the platform carries no series yet.
//   3. FROM WHERE — `dataset`, the named public dataset the series is (or would
//      be) built from. Never a guess: a provider, a dataset code where one
//      exists, and a URL. Families with an empty `indicatorIds` are therefore
//      *specified but not yet built* — the module shows them as a measurement
//      gap with the pull recipe attached, and nothing is invented to fill them.
//
// Matching is deterministic, in the same style as
// scripts/policy-targets-classify.mjs: word-boundary terms, a trailing "*" makes
// a stem, `strong` terms weigh double, `veto` phrases suppress known traps. No
// agent judgement runs at build time — `npm run build:target-indicators`
// reproduces the mapping exactly from this file plus the overrides.
//
// AI-compiled — pending Secretariat verification. The vocabularies and the
// family/target fit are the part a reviewer should challenge first; corrections
// are carried in scripts/target-indicators-overrides.json, never hand-edited
// into the generated file.
// ---------------------------------------------------------------------------

