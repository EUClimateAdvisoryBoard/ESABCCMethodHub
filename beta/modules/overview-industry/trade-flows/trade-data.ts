const ZERO_FLOWS: TecFlows = { impExt: 0, expExt: 0, impInt: 0, expInt: 0 };

/**
 * The 24-division backbone. Values come from the generated Eurostat extract
 * (`ext_tec01`, EU-27, € bn) — regenerate with
 * `node scripts/fetch-trade-flows-io-data.mjs`.
 */
export const DIVISION_TRADE: DivisionTrade[] = DIVISION_META.map((m) => ({
  ...m,
  flows: {
    '2023': TEC_BACKBONE[m.code]?.['2023'] ?? ZERO_FLOWS,
    '2024': TEC_BACKBONE[m.code]?.['2024'] ?? ZERO_FLOWS,
  },
}));

/**
 * Official Section C aggregate row of ext_tec01, by year. NOTE: this does NOT
 * equal the sum of the 24 published divisions (2023 extra-EU imports: €975.7 bn
 * aggregate vs €927.1 bn summed) — the aggregate additionally covers trade that
 * cannot be allocated to a specific division (enterprise-register gaps,
 * confidentiality). Both are exposed; the methodology view explains the gap.
 */
export const SECTION_C_TEC: Record<TecYear, TecFlows> = {
  '2023': TEC_BACKBONE['C']['2023'],
  '2024': TEC_BACKBONE['C']['2024'],
};

/** Sum of the 24 published divisions, by year (for the aggregation-gap note). */
export const SECTION_C_DIVISION_SUM: Record<TecYear, TecFlows> = (() => {
  const sum = (year: TecYear): TecFlows => {
    const t = { impExt: 0, expExt: 0, impInt: 0, expInt: 0 };
    for (const d of DIVISION_TRADE) {
      t.impExt += d.flows[year].impExt;
      t.expExt += d.flows[year].expExt;
      t.impInt += d.flows[year].impInt;
      t.expInt += d.flows[year].expInt;
    }
    return {
      impExt: Math.round(t.impExt * 10) / 10,
      expExt: Math.round(t.expExt * 10) / 10,
      impInt: Math.round(t.impInt * 10) / 10,
      expInt: Math.round(t.expInt * 10) / 10,
    };
  };
  return { '2023': sum('2023'), '2024': sum('2024') };
})();

