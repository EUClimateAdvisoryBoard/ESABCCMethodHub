/**
 * Overview Industry — Trade flows (data model).
 * ---------------------------------------------
 * An input–output view of EU-27 manufacturing trade: for every NACE Rev. 2
 * Section C division (10–33) it maps
 *   • OUTPUT  → where EU manufacturing sells (intra-EU vs extra-EU, real
 *               destination shares),
 *   • INPUT   → what it must import and from where — at three depths:
 *               (1) the imported-intermediate-input mix straight out of the
 *                   EU-27 input–output use table (which products, € bn, what
 *                   share of all inputs is imported),
 *               (2) origin countries of those imports from the FIGARO
 *                   inter-country input–output framework, and
 *               (3) a curated critical-materials layer (EC/JRC) naming the
 *                   specific feedstocks below the 2-digit radar, and
 *   • RISK    → the hotspots where imports are both large and concentrated in
 *               a single supplier (carbon-leakage / CBAM / CRMA front line).
 *
 * DATA ARCHITECTURE (three layers, see the Methodology view for the full story):
 *
 *   Layer 1 — TRADE BACKBONE (statistical, all 24 divisions)
 *     Eurostat `ext_tec01`, EU-27, 2023 + 2024: extra-/intra-EU imports and
 *     exports by the NACE activity of the trading ENTERPRISE. Fetched live and
 *     regenerated by `scripts/fetch-trade-flows-io-data.mjs` into
 *     `eurostat-io.generated.ts`.
 *
 *   Layer 2 — INPUT–OUTPUT LAYER (statistical, PRODUCT-based, 2023)
 *     • EU-27 use table at basic prices (`naio_10_cp1610`): each industry's
 *       intermediate inputs by product, split domestic vs imported.
 *     • FIGARO application datasets (`naio_10_fgti`, `naio_10_fgte`,
 *       `naio_10_fgfoee`): import origins, export destinations and the foreign
 *       value added embedded in exports, by counterpart country.
 *     Enterprise-based (layer 1) and product-based (layer 2) numbers
 *     deliberately DIFFER — C19 is the textbook case (refiners import crude,
 *     but crude is a MINING product) — and the module explains that instead of
 *     hiding it.
 *
 *   Layer 3 — DEPENDENCY LAYER (curated, "as reported by <source>")
 *     Critical-raw-materials shares (EC/JRC, CRMA), strategic-dependency
 *     reviews (SWD(2021) 352) and named per-sector inputs. These are NOT
 *     derivable from official statistics at this granularity; every figure
 *     carries its source and should be read as that source's assessment.
 *
 * SOURCING RULE (hard): every figure carries a real, working source link.
 * Nothing is invented.
 *
 * Reuses the `Source` / `Sourced` primitives from the Clean Tech catalogue so
 * the two sub-pages share one evidence model.
 */

